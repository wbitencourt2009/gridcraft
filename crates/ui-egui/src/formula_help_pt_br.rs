/// Renames every parameter of an English catalog argument list (`number1, [number2], ...`).
pub(crate) fn localize_params(args: &str) -> String {
    let mut out = String::with_capacity(args.len() + 16);
    let mut word = String::new();
    let flush = |word: &mut String, out: &mut String| {
        if word.is_empty() {
            return;
        }
        let base = word.trim_end_matches(|c: char| c.is_ascii_digit());
        let digits = &word[base.len()..];
        match PARAMS.iter().find(|(en, _)| *en == base) {
            Some((_, pt)) => {
                out.push_str(pt);
                out.push_str(digits);
            }
            None => out.push_str(word),
        }
        word.clear();
    };
    for c in args.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            word.push(c);
        } else {
            flush(&mut word, &mut out);
            out.push(c);
        }
    }
    flush(&mut word, &mut out);
    out
}

pub(crate) fn description(canonical: &str) -> Option<&'static str> {
    DESCRIPTIONS.iter().find(|(name, _)| name.eq_ignore_ascii_case(canonical)).map(|(_, d)| *d)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_catalog_function_has_portuguese_help() {
        for f in gridcraft_engine::cmd::formulas::function_list() {
            let name = f["name"].as_str().unwrap();
            assert!(description(name).is_some(), "{name} has no pt-BR description");
            let sig = f["signature"].as_str().unwrap();
            let args = sig.split_once('(').map(|(_, a)| a).unwrap_or("");
            let mut word = String::new();
            for c in args.chars().chain([' ']) {
                if c.is_ascii_alphanumeric() || c == '_' {
                    word.push(c);
                } else if !word.is_empty() {
                    let base = word.trim_end_matches(|c: char| c.is_ascii_digit());
                    assert!(PARAMS.iter().any(|(en, _)| *en == base), "{name}: parameter {word} has no pt-BR name");
                    word.clear();
                }
            }
        }
        assert_eq!(DESCRIPTIONS.len(), gridcraft_engine::cmd::formulas::function_list().len());
    }

    #[test]
    fn vlookup_parameters_follow_the_portuguese_convention() {
        assert_eq!(
            localize_params("lookup_value, table_array, col_index_num, [range_lookup])"),
            "valor_procurado, matriz_tabela, núm_índice_coluna, [procurar_intervalo])"
        );
        assert_eq!(localize_params("number1, [number2], ...)"), "núm1, [núm2], ...)");
    }
}
